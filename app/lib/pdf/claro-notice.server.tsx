import {
	Document,
	Page,
	renderToBuffer,
	StyleSheet,
	Text,
	View,
} from "@react-pdf/renderer"

const styles = StyleSheet.create({
	page: { padding: 40, fontFamily: "Helvetica", fontSize: 9 },
	title: {
		fontSize: 13,
		fontWeight: "bold",
		textAlign: "center",
		marginBottom: 4,
	},
	subtitle: {
		fontSize: 9,
		textAlign: "center",
		marginBottom: 12,
		color: "#555",
	},
	headerRow: {
		flexDirection: "row",
		justifyContent: "space-between",
		marginBottom: 3,
	},
	label: { color: "#555" },
	section: { marginTop: 10 },
	sectionTitle: { fontWeight: "bold", marginBottom: 4, fontSize: 9 },
	tableHeader: {
		flexDirection: "row",
		backgroundColor: "#e2e8f0",
		padding: 3,
		fontSize: 8,
	},
	tableRow: {
		flexDirection: "row",
		padding: 3,
		borderBottom: "0.5px solid #cbd5e1",
		fontSize: 8,
	},
	c1: { flex: 1.5 },
	c2: { flex: 3 },
	c3: { flex: 1, textAlign: "right" },
	signature: { marginTop: 24, borderTop: "1px solid #ccc", paddingTop: 12 },
})

interface NoticeLineItem {
	claroCode: string
	name: string
	qty: number
	unit: string
}

/**
 * Claro-issued closeout notice ("Hoja de Cierre") — this is received from
 * Claro's own system and uploaded by the supervisor, not generated by this
 * app. This generator exists only to produce a realistic placeholder for
 * demo data.
 */
export async function generateClaroNoticePdf(params: {
	avisoNumber: string
	jobType: string
	jobAddress: string
	assignedTo: string
	lineItems: NoticeLineItem[]
}): Promise<Buffer> {
	const element = (
		<Document>
			<Page size="LETTER" style={styles.page}>
				<Text style={styles.title}>HOJA DE CIERRE FINAL</Text>
				<Text style={styles.subtitle}>Aviso #{params.avisoNumber}</Text>

				<View style={styles.headerRow}>
					<Text>
						<Text style={styles.label}>Título: </Text>
						{params.jobType}
					</Text>
					<Text>
						<Text style={styles.label}>Asignado a: </Text>
						{params.assignedTo}
					</Text>
				</View>
				<View style={styles.headerRow}>
					<Text>
						<Text style={styles.label}>Dirección: </Text>
						{params.jobAddress}
					</Text>
					<Text>
						<Text style={styles.label}>Contratista: </Text>
						JAF Communications Inc
					</Text>
				</View>

				<View style={styles.section}>
					<Text style={styles.sectionTitle}>Servicios Realizados Totales</Text>
					<View style={styles.tableHeader}>
						<Text style={styles.c1}>Item</Text>
						<Text style={styles.c2}>Descripción</Text>
						<Text style={styles.c3}>Cantidad</Text>
					</View>
					{params.lineItems.map((item) => (
						<View key={item.claroCode} style={styles.tableRow}>
							<Text style={styles.c1}>{item.claroCode}</Text>
							<Text style={styles.c2}>{item.name}</Text>
							<Text style={styles.c3}>
								{item.qty} {item.unit}
							</Text>
						</View>
					))}
				</View>

				<View style={styles.signature}>
					<Text>Supervisor de Claro aprobó trabajos realizados.</Text>
					<Text style={{ marginTop: 8 }}>
						Firma Supervisor Claro: ___________________
					</Text>
				</View>
			</Page>
		</Document>
	)

	return renderToBuffer(element)
}
