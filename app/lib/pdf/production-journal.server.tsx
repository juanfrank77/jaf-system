import {
	Document,
	Page,
	renderToBuffer,
	StyleSheet,
	Text,
	View,
} from "@react-pdf/renderer"
import type { PayrollSheetLine } from "~/lib/payroll-run.server"

const styles = StyleSheet.create({
	page: { padding: 28, fontFamily: "Helvetica", fontSize: 9 },
	header: {
		flexDirection: "row",
		justifyContent: "space-between",
		marginBottom: 8,
	},
	title: { fontSize: 13, fontWeight: "bold" },
	period: { fontSize: 9, color: "#555" },
	tableHeader: {
		flexDirection: "row",
		borderBottom: "0.5px solid #666",
		fontSize: 7,
		textTransform: "uppercase",
		letterSpacing: 0.3,
		marginTop: 8,
	},
	row: { flexDirection: "row", borderBottom: "0.25px solid #ddd" },
	totalRow: {
		flexDirection: "row",
		fontWeight: "bold",
		borderTop: "1px solid #333",
		marginTop: 2,
	},
	cell: { paddingHorizontal: 2, paddingVertical: 2 },
	muted: { color: "#555" },
	footer: { marginTop: 12, fontSize: 6, color: "#777", textAlign: "center" },
})

const COL = {
	brigade: 150,
	avisos: 190,
	net: 60,
	ret: 60,
	toPay: 70,
} as const

const fmt = (n: number) => n.toFixed(2)

/**
 * Render the payroll request sheet Carmen pays from: one line per brigade with
 * the Aviso #s it covers, net (65% of the pre-IVU labor, 80% on D rows), the 10% retention and
 * what to pay. It is built from `PayrollSheetLine`, which has no gross and no
 * service-line detail, so the JAF price cannot reach Carmen's page (Rule 6).
 */
export async function generateProductionJournalPdf(
	run: { label: string },
	lines: PayrollSheetLine[],
): Promise<Buffer> {
	const total = lines.reduce(
		(acc, l) => ({
			net: acc.net + l.net,
			retention: acc.retention + l.retention,
			toPay: acc.toPay + l.toPay,
		}),
		{ net: 0, retention: 0, toPay: 0 },
	)
	const doc = (
		<Document>
			<Page size="LETTER" style={styles.page}>
				<View style={styles.header}>
					<Text style={styles.title}>Payroll request — {run.label}</Text>
					<Text style={styles.period}>Period {run.label}</Text>
				</View>
				<Text style={styles.muted}>
					{lines.length} brigades,{" "}
					{new Set(lines.flatMap((l) => l.avisoNumbers)).size} Avisos
				</Text>

				<View style={styles.tableHeader}>
					<Text style={[styles.cell, { width: COL.brigade }]}>Brigade</Text>
					<Text style={[styles.cell, { width: COL.avisos }]}>Avisos</Text>
					<Text style={[styles.cell, { width: COL.net, textAlign: "right" }]}>
						Net
					</Text>
					<Text style={[styles.cell, { width: COL.ret, textAlign: "right" }]}>
						10% ret.
					</Text>
					<Text style={[styles.cell, { width: COL.toPay, textAlign: "right" }]}>
						To pay
					</Text>
				</View>
				{lines.map((l) => (
					<View key={l.brigadeCode} style={styles.row} wrap={false}>
						<Text style={[styles.cell, { width: COL.brigade }]}>
							{l.brigadeCode} — {l.brigadeLabel}
							{l.unverified ? " (D · 80%, ret. unverified)" : ""}
						</Text>
						<Text style={[styles.cell, { width: COL.avisos }]}>
							{l.avisoNumbers.join(" · ") || "—"}
						</Text>
						<Text style={[styles.cell, { width: COL.net, textAlign: "right" }]}>
							{fmt(l.net)}
						</Text>
						<Text style={[styles.cell, { width: COL.ret, textAlign: "right" }]}>
							{fmt(l.retention)}
						</Text>
						<Text
							style={[styles.cell, { width: COL.toPay, textAlign: "right" }]}
						>
							{fmt(l.toPay)}
						</Text>
					</View>
				))}
				<View style={styles.totalRow}>
					<Text style={[styles.cell, { width: COL.brigade + COL.avisos }]}>
						Total
					</Text>
					<Text style={[styles.cell, { width: COL.net, textAlign: "right" }]}>
						{fmt(total.net)}
					</Text>
					<Text style={[styles.cell, { width: COL.ret, textAlign: "right" }]}>
						{fmt(total.retention)}
					</Text>
					<Text style={[styles.cell, { width: COL.toPay, textAlign: "right" }]}>
						{fmt(total.toPay)}
					</Text>
				</View>

				<Text style={styles.footer}>
					Net is on pre-IVU labor. Generated by the JAF Ops system.
				</Text>
			</Page>
		</Document>
	)
	return renderToBuffer(doc)
}
