/**
 * One-pass extract + .jaf- prefix of the design-system kernel CSS.
 * Reads JAF_Ops_Design_System_Guide.html; writes app/styles/jaf-ops.css.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const html = fs.readFileSync(
	path.join(root, "JAF_Ops_Design_System_Guide.html"),
	"utf8",
)
const begin = html.indexOf("/* >>> JAF OPS KERNEL — BEGIN >>> */")
const end = html.indexOf("/* <<< JAF OPS KERNEL — END <<< */")
if (begin < 0 || end < 0) throw new Error("kernel markers not found")

let css = html.slice(begin, end)

css = css.replace(/:root\{[\s\S]*?\n  \}/, "")
css = css.replace(/@media \(prefers-color-scheme:dark\)\{[\s\S]*?\n  \}/, "")
css = css.replace(/:root\[data-theme="dark"\]\{[\s\S]*?\n  \}/, "")
css = css.replace(/\s*\*\{ box-sizing:border-box; \}/, "")
css = css.replace(/\s*html,body\{[^}]+\}/, "")
css = css.replace(/\s*body\{ font-family:[^}]+\}/, "")

css = css.replace(/\.([a-zA-Z][a-zA-Z0-9_-]*)/g, (match, name) => {
	if (name.startsWith("jaf-")) return match
	return `.jaf-${name}`
})

// Bare element rules that start a selector would restyle the whole app.
css = css.replace(
	/(^|,)(\s*)(table|thead|tbody|tfoot|tr|th|td|footer)(?=[\s,{.:[])/gm,
	"$1$2.jaf-ds $3",
)

const header = `/* Generated by scripts/extract-jaf-css.mjs — do not hand-edit.
   Kernel component CSS. Class names are prefixed with .jaf- to avoid
   Tailwind / shadcn collisions. Tokens are declared on .jaf-ds in app.css. */

`

const dest = path.join(root, "app/styles/jaf-ops.css")
fs.mkdirSync(path.dirname(dest), { recursive: true })
fs.writeFileSync(dest, header + css.trimStart())
console.log(`wrote ${dest} (${header.length + css.trimStart().length} bytes)`)
